#!/usr/bin/env python3
"""Embed the lilo-ui dist bundle into Swift constants served over lilo-chrome:// (zero disk IO)."""
import os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
dist_dir = os.path.join(root, "build", "chrome-ui")
output_path = os.path.join(root, "Lilo", "Generated", "ChromeUIAssets.swift")

# Total-bundle budget: a runaway bundle fails the build in CI rather than silently bloating the
# binary and slowing cold start.
# Six locales fit the base budget. Additional deferred message and emoji catalogs get
# 280 KB each, enough for the largest existing locale without growing the first-frame budget.
catalog_dir = os.path.join(root, "lilo-ui", "src", "lib", "i18n", "locales")
catalog_count = sum(name.endswith(".json") for name in os.listdir(catalog_dir))
max_embedded_bytes = 2_032_500 + max(0, catalog_count - 6) * 280_000
# The part of it loaded before the chrome's first frame, which every launch parses.
# Includes script-aware locale resolution and registration; catalogs stay deferred.
max_first_frame_bytes = 576_200 + max(0, catalog_count - 6) * 128

mime_types = {
    ".html": "text/html",
    ".js": "text/javascript",
    ".css": "text/css",
    ".svg": "image/svg+xml",
    ".json": "application/json",
}

if not os.path.isdir(dist_dir):
    print(f"error: {dist_dir} not found: run make ui-build first", file=sys.stderr)
    sys.exit(1)

assets = []
total_bytes = 0
for dirpath, _, filenames in os.walk(dist_dir):
    for name in sorted(filenames):
        path = os.path.join(dirpath, name)
        rel = os.path.relpath(path, dist_dir).replace(os.sep, "/")
        ext = os.path.splitext(name)[1]
        if ext not in mime_types:
            print(f"error: {rel}: unsupported asset type '{ext}' (text-only embed)", file=sys.stderr)
            sys.exit(1)
        with open(path, "r", encoding="utf-8") as f:
            content = f.read()
        total_bytes += len(content.encode("utf-8"))
        assets.append((rel, mime_types[ext], content))

if not any(rel == "index.html" for rel, _, _ in assets):
    print("error: dist has no index.html", file=sys.stderr)
    sys.exit(1)

if total_bytes > max_embedded_bytes:
    print(
        f"error: embedded chrome UI is {total_bytes:,} bytes; budget is {max_embedded_bytes:,} bytes",
        file=sys.stderr,
    )
    sys.exit(1)

# What the chrome loads before its first frame: index.html and what it references (the entry script, the
# chunks it preloads, the stylesheets). The rest loads after; grow this only for what the first frame shows.
sizes = {rel: len(content.encode("utf-8")) for rel, _, content in assets}
index_html = next(content for rel, _, content in assets if rel == "index.html")
first_frame = ["index.html"] + re.findall(r'(?:src|href)="\./([^"]+)"', index_html)
first_frame_bytes = sum(sizes.get(rel, 0) for rel in first_frame)
if first_frame_bytes > max_first_frame_bytes:
    print(
        f"error: the chrome's first frame loads {first_frame_bytes:,} bytes ({', '.join(first_frame)}); "
        f"budget is {max_first_frame_bytes:,} bytes",
        file=sys.stderr,
    )
    sys.exit(1)

# High raw-string delimiter count avoids escaping the minified payloads.
delimiter = "#" * 8
entries = []
for rel, mime, content in sorted(assets):
    entries.append(
        f'        "{rel}": Asset(mimeType: "{mime}", text: {delimiter}"""\n{content}\n"""{delimiter})'
    )

swift = f"""// Auto-generated by scripts/embed_chrome_ui.py: run make ui-build to regenerate.
import Foundation

enum ChromeUIAssets {{
    struct Asset {{
        let mimeType: String
        /// Static storage lets the scheme handler serve it as Data without copying.
        let text: StaticString
    }}

    static let assets: [String: Asset] = [
{("," + os.linesep).join(entries)}
    ]
}}
"""

# Unchanged output keeps its mtime, so the next Xcode build skips recompiling it.
try:
    with open(output_path, encoding="utf-8") as f:
        unchanged = f.read() == swift
except FileNotFoundError:
    unchanged = False
if not unchanged:
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(swift)

print(f"Embedded {len(assets)} assets, {total_bytes:,} bytes to ChromeUIAssets.swift")
