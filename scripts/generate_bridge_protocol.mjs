#!/usr/bin/env node
// Generates the tab bridge TypeScript and Swift from bridge-schema/tab.json (`make bridge-gen`).
// Plain Node ESM, no dependencies.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

const schemaPath = resolve(root, "bridge-schema/tab.json");
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const fields = schema.fields;

// ---------------------------------------------------------------------------
// Pure generation functions (exported for the freshness test)
// ---------------------------------------------------------------------------

export function generateTS(fields) {
  // BridgeTabSnapshot interface
  const ifaceLines = fields.map((f) => {
    const optMark = f.tsOptional ? "?" : "";
    let tsType;
    if (f.type === "string") tsType = "string";
    else if (f.type === "bool") tsType = "boolean";
    else if (f.type === "double") tsType = "number";
    else throw new Error(`Unknown type: ${f.type}`);
    return `\t${f.name}${optMark}: ${tsType};`;
  });

  // Preamble locals for coerceTabSnapshot (before the return {})
  const preambleLines = [];
  for (const f of fields) {
    if (!f.coerce) continue;
    if (f.coerce === "trimmedNonEmptyString") {
      if (f.tsOptional) {
        preambleLines.push(`\tconst ${f.name} = coerceTrimmedOptional(data.${f.name});`);
      } else {
        // Non-optional trimmedNonEmptyString: local var used as reference (e.g. url for title coerce)
        preambleLines.push(`\tconst ${f.name} = data.${f.name} ?? "";`);
      }
    } else if (f.coerce === "hexColor") {
      preambleLines.push(`\tconst ${f.name} = coerceHexColor(data.${f.name});`);
    } else if (f.coerce === "title") {
      // no preamble needed; inline in snapshot body
    } else {
      throw new Error(`Unknown coerce kind: "${f.coerce}" on field "${f.name}"`);
    }
  }

  // coerceTabSnapshot body
  const snapshotLines = fields.map((f) => {
    if (f.coerce === "title") return `\t\t${f.name}: normalizeTabTitle(data.${f.name}, url),`;
    if (f.coerce === "trimmedNonEmptyString" || f.coerce === "hexColor") return `\t\t${f.name},`;
    if (f.tsDefault !== undefined) return `\t\t${f.name}: data.${f.name} ?? ${f.tsDefault},`;
    // tsOptional with no default: pass through
    return `\t\t${f.name}: data.${f.name},`;
  });

  // coerceTabPatch body
  const patchLines = fields.map((f) => {
    if (f.tsPatchSkip) return null;
    if (f.coerce === "title") {
      return `\tif (data.${f.name} !== undefined) out.${f.name} = normalizeTabTitle(data.${f.name}, data.url);`;
    }
    if (f.coerce === "trimmedNonEmptyString") {
      if (f.tsOptional) {
        return `\tif (data.${f.name} !== undefined) out.${f.name} = coerceTrimmedOptional(data.${f.name});`;
      } else {
        // Non-optional: plain passthrough (cannot become undefined)
        return `\tif (data.${f.name} !== undefined) out.${f.name} = data.${f.name};`;
      }
    }
    if (f.coerce === "hexColor") {
      return `\tif (data.${f.name} !== undefined) out.${f.name} = coerceHexColor(data.${f.name});`;
    }
    if (f.coerce) throw new Error(`Unknown coerce kind: "${f.coerce}" on field "${f.name}"`);
    return `\tif (data.${f.name} !== undefined) out.${f.name} = data.${f.name};`;
  }).filter(Boolean);

  return [
    "// GENERATED by scripts/generate_bridge_protocol.mjs from bridge-schema/tab.json, DO NOT EDIT",
    "// Re-run: make bridge-gen",
    "",
    'import { normalizeTabTitle, coerceTrimmedOptional, coerceHexColor } from "./coerceHelpers";',
    "",
    "type TabLike = Partial<BridgeTabSnapshot> & { id: string; spaceId?: string };",
    "",
    "export interface BridgeTabSnapshot {",
    ...ifaceLines,
    "}",
    "",
    "export function coerceTabSnapshot(data: TabLike): BridgeTabSnapshot {",
    ...preambleLines,
    "\treturn {",
    ...snapshotLines,
    "\t};",
    "}",
    "",
    "/**",
    " * Coerce a runtime tab patch: only the fields actually present in `data` are returned, so the",
    " * caller can merge them onto the existing tab without clobbering omitted fields (e.g. the favicon,",
    " * which runtime patches deliberately omit) with defaults.",
    " */",
    "export function coerceTabPatch(data: TabLike): Partial<BridgeTabSnapshot> {",
    "\tconst out: Partial<BridgeTabSnapshot> = {};",
    ...patchLines,
    "\treturn out;",
    "}",
    "",
  ].join("\n");
}

export function generateSwift(fields) {
  // All fields go into the Swift enum (including windowId which is in bridgeData but not TS)
  const swiftFields = fields;

  const caseLines = swiftFields.map((f) => `\tcase ${f.name} = "${f.name}"`);

  const runtimeExcludedCases = swiftFields
    .filter((f) => f.runtime === false)
    .map((f) => `\t\t\t.${f.name}`)
    .join(",\n");

  return [
    "// GENERATED by scripts/generate_bridge_protocol.mjs from bridge-schema/tab.json, DO NOT EDIT",
    "// Re-run: make bridge-gen",
    "",
    "// swiftlint:disable redundant_string_enum_value",
    "/// Wire keys for the tab bridge payload, generated from bridge-schema/tab.json.",
    "/// Adding a field to the schema produces a compile error in Tab.bridgeData until Swift handles it.",
    "enum TabBridgeField: String, CaseIterable {",
    ...caseLines,
    "// swiftlint:enable redundant_string_enum_value",
    "",
    "\t/// Fields excluded from runtime patches (progress/loading/nav-flag ticks).",
    "\t/// Full snapshots and sidebarChanged upserts still carry these.",
    "\tstatic let runtimeExcluded: Set<TabBridgeField> = [",
    runtimeExcludedCases,
    "\t]",
    "}",
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------------
// Write outputs (only when run directly, not when imported by the freshness test)
// ---------------------------------------------------------------------------

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tsOut = resolve(root, "lilo-ui/src/lib/bridge/tabProtocol.gen.ts");
  const swiftOut = resolve(root, "Lilo/Generated/TabBridgeSchema.gen.swift");

  // Unchanged outputs keep their mtime, so incremental builds skip them.
  for (const [path, content] of [[tsOut, generateTS(fields)], [swiftOut, generateSwift(fields)]]) {
    if (existsSync(path) && readFileSync(path, "utf8") === content) continue;
    writeFileSync(path, content, "utf8");
    console.log(`wrote ${path}`);
  }
}
