#!/usr/bin/env python3
"""Generate Lilo/Generated/NativeStrings.swift from the i18n catalog's "native" namespace.

The i18n JSON catalogs are the single source of truth for every translation. This emits the
native (AppKit) tables as compiled Swift constants (the same embed-at-build-time pattern
as embed_chrome_ui.py), so native menus/dialogs and the web UI share one place to translate.
"""
import json
import os
from glob import glob

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
catalog_dir = os.path.join(root, "lilo-ui", "src", "lib", "i18n", "locales")
output_path = os.path.join(root, "Lilo", "Generated", "NativeStrings.swift")


def swift_escape(value):
    return (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )


tables = []
locales = []
entry_count = 0
for path in sorted(glob(os.path.join(catalog_dir, "*.json"))):
    locale = os.path.splitext(os.path.basename(path))[0]
    if locale == "en":
        continue
    with open(path, encoding="utf-8") as f:
        native = json.load(f)["native"]
    rows = [f'        "{swift_escape(k)}": "{swift_escape(native[k])}",' for k in sorted(native)]
    if rows:
        rows[-1] = rows[-1].rstrip(",")  # swiftlint forbids a trailing comma in collection literals
    body = "\n".join(rows)
    identifier = locale.replace("-", "_")
    tables.append(f'    private static let {identifier}: [String: String] = [\n{body}\n    ]')
    locales.append(locale)
    entry_count += len(native)
body = "\n\n".join(tables)
locale_names = ", ".join(f'"{locale}"' for locale in ["en", *locales])
cases = "\n".join(f'        case "{locale}": return {locale.replace("-", "_")}[key] ?? key' for locale in locales)

swift = f"""// Auto-generated by scripts/generate_native_strings.py: run make ui-build to regenerate.
// Source of truth: lilo-ui/src/lib/i18n/locales/*.json (the "native" namespace).
enum NativeStrings {{
    static let locales: Set<String> = [{locale_names}]

    static func translate(_ key: String, locale: String) -> String {{
        switch locale {{
{cases}
        default: return key
        }}
    }}

{body}
}}
"""

# Unchanged output keeps its mtime, so the next Xcode build skips recompiling it.
try:
    with open(output_path, encoding="utf-8") as f:
        unchanged = f.read() == swift
except FileNotFoundError:
    unchanged = False
if not unchanged:
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(swift)

print(f"Generated NativeStrings.swift with {entry_count} entries across {len(tables)} locales")
