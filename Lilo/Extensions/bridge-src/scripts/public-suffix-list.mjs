// Writes Lilo/Extensions/public-suffix-list.dat for chrome.publicSuffix: every rule, ICANN and private as Chrome has
// both, canonicalized like a URL host (lowercase, punycode), and the command bar's top-level domains taken from it.
// Usage: `make public-suffix-list`.
import { writeFileSync } from 'node:fs';
import { domainToASCII } from 'node:url';

const response = await fetch('https://publicsuffix.org/list/public_suffix_list.dat');
if (!response.ok) throw new Error(`Public Suffix List download failed: ${response.status}`);
const lines = (await response.text()).split('\n');

const header = lines.filter((line) => /^\/\/ (This Source Code|License, v|file, You|VERSION:|COMMIT:)/.test(line));
const rules = [];
for (const line of lines) {
  const rule = line.trim().split(/\s/)[0];
  if (!rule || rule.startsWith('//')) continue;
  const prefix = rule.startsWith('!') ? '!' : rule.startsWith('*.') ? '*.' : '';
  const host = domainToASCII(rule.slice(prefix.length));
  if (!host) throw new Error(`Unparsable rule: ${rule}`);
  rules.push(prefix + host);
}

writeFileSync(new URL('../../public-suffix-list.dat', import.meta.url), `${[...header, ...rules].join('\n')}\n`);
console.log(`Wrote ${rules.length} rules`);

// A one-label rule, or the base of a one-label wildcard like `*.ck`, is a top-level domain.
const topLevel = [...new Set(rules.map((rule) => rule.replace(/^\*\./, '')).filter((rule) => !/[.!]/.test(rule)))].sort();
const wrapped = [];
for (const domain of topLevel) {
  if (wrapped.length && wrapped.at(-1).length + domain.length < 100) wrapped[wrapped.length - 1] += ` ${domain}`;
  else wrapped.push(domain);
}
writeFileSync(
  new URL('../../../../lilo-ui/src/lib/topLevelDomains.gen.ts', import.meta.url),
  '// Generated by Lilo/Extensions/bridge-src/scripts/public-suffix-list.mjs (make public-suffix-list): do not edit.\n' +
    '// Every top-level domain of the Public Suffix List in lowercase punycode, separated by whitespace.\n' +
    `export const TOP_LEVEL_DOMAINS = \`${wrapped.join('\n')}\`;\n`,
);
console.log(`Wrote ${topLevel.length} top-level domains`);
